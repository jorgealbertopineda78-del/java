public class App {
    public static int suma(int a, int b) {
        return a + b;
    }

    public static void main(
        g[] args) throws Exception {
        System.out.println("Hello, World!");

        // Demostración de la función suma
        int a = 3;
        int b = 4;
        System.out.println("suma(" + a + ", " + b + ") = " + suma(a, b));
    }
}
